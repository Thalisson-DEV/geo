/** Nomes que só representam animação no PrimeIcons e não viram ícone. */
const MODIFICADORES_PI = new Set(['pi', 'pi-spin', 'pi-fw']);

/**
 * Resolve um nome Lucide ("check") ou uma classe PrimeIcons ("pi pi-check pi-spin") para o
 * ícone registrado. Devolve `undefined` quando não há equivalente.
 */
export function resolverIcone(nome: string | null | undefined): { nome: GeoIconeNome; girar: boolean } | undefined {
  if (!nome) return undefined;
  const partes = nome.trim().split(/\s+/);
  const girar = partes.includes('pi-spin');
  for (const parte of partes) {
    if (MODIFICADORES_PI.has(parte)) continue;
    if (parte in GEO_ICONES) return { nome: parte as GeoIconeNome, girar };
    if (parte.startsWith('pi-')) {
      const lucide = PI_PARA_LUCIDE[parte.slice(3)];
      if (lucide) return { nome: lucide, girar };
    }
  }
  return undefined;
}
